def answer_messages(question: str, context_blocks: list[str], history: list[tuple[str, str]]) -> list[dict]:
    ctx = "\n\n".join(context_blocks)
    hist = ""
    if history:
        hist = "المحادثة السابقة:\n" + "\n".join(f"المستخدم: {q}\nالمساعد: {a}" for q, a in history[-2:]) + "\n\n"
    user = f"السياق:\n{ctx}\n\n{hist}السؤال: {question}\n\nالجواب:"
    return [{"role": "system", "content": ANSWER_SYSTEM}, {"role": "user", "content": user}]


def simple_messages(system: str, question: str, extra: str = "") -> list[dict]:
    return [{"role": "system", "content": system},
            {"role": "user", "content": (extra + "\n" if extra else "") + f"السؤال: {question}\n\nالرد:"}]
