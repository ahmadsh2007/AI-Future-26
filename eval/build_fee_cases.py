def norm(s):
    return re.sub(r"\s+", " ", s).strip()


def load_lines(service):
    with open(os.path.join(DATA, service + ".txt"), encoding="utf-8") as f:
        return [norm(l) for l in f if norm(l)]


def resolve(service, key):
    sub = KEYS[service][key]
    hits = [l for l in load_lines(service) if sub in l]
    if len(hits) != 1:
        raise SystemExit("key %s/%s matched %d lines" % (service, key, len(hits)))
    return hits[0]


def C(service, who, must, total, must_not, keys):
    return {"service": service, "who": who, "must_amounts": must, "total": total,
            "must_not_amounts": must_not,
            "lines": [resolve(service, k) for k in keys]}


